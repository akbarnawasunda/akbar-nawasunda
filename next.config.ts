import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  async headers() {
    return [
      {
        // Anti-framing for NAWA STUDIO only. These patterns use Next.js path matching: `/studio/:path*`
        // matches /studio/ and every nested route, and never matches /studio-anything or the public site.
        // This is clickjacking defence only; authentication and authorization are enforced in code.
        source: "/studio",
        headers: [
          { key: "Content-Security-Policy", value: "frame-ancestors 'none'" },
          { key: "X-Frame-Options", value: "DENY" },
        ],
      },
      {
        source: "/studio/:path*",
        headers: [
          { key: "Content-Security-Policy", value: "frame-ancestors 'none'" },
          { key: "X-Frame-Options", value: "DENY" },
        ],
      },
    ];
  },
};

export default nextConfig;
